export type TopicStatus = 'not_started' | 'learning' | 'practised' | 'revised';

export type ImportanceLevel = 'High' | 'Medium' | 'Low';

export interface SubjectMeta {
  id: SubjectId;
  name: string;
  shortName: string;
  expectedMarks: number;
  phaseNumber: 1 | 2 | 3 | 4 | 5;
  accentHex: string;
}

export interface SyllabusTopic {
  id: string;
  subjectId: SubjectId;
  title: string;
  status: TopicStatus;
  importance: ImportanceLevel;
  videoUrl: string;
  notesUrl: string;
  /** Spaced repetition tracking when marked 'practised' or 'revised' */
  practisedDate?: string; // YYYY-MM-DD
  revisionStage?: number; // index into [1, 3, 7, 21, 45]
  nextRevisionDate?: string; // YYYY-MM-DD
  lastRevisedDate?: string; // YYYY-MM-DD
}

